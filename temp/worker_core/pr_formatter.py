"""
PR Comment Formatter for SentinAI Security Results.
Generates GitHub-flavored markdown for PR comments.
"""

from typing import Dict, Any, List
import json


def format_finding_for_pr(finding: Dict[str, Any]) -> str:
    """Format a single finding for PR comment."""
    severity = finding.get("severity", "MEDIUM")
    finding_type = finding.get("type", "Unknown")
    file_path = finding.get("file", finding.get("filename", "Unknown"))
    line = finding.get("line", 1)
    description = finding.get("description", finding.get("reason", "No description"))
    vulnerable_code = finding.get("vulnerable_code", "")
    confidence = finding.get("confidence_score", finding.get("confidence", 0.8))

    # Severity emoji
    severity_icons = {
        "CRITICAL": "🔴",
        "HIGH": "🟠",
        "MEDIUM": "🟡",
        "LOW": "🔵"
    }
    icon = severity_icons.get(severity.upper(), "⚪")

    # Format code snippet
    code_block = ""
    if vulnerable_code:
        # Detect language from file extension
        lang = _detect_language(file_path)
        code_block = f"\n```{lang}\n{vulnerable_code[:300]}\n```\n"

    # Build the finding section
    section = f"""
### {icon} {severity}: {finding_type}

**File:** `{file_path}` (line {line})  
**Confidence:** {confidence:.0%}  
**Description:** {description}{code_block}
"""

    # Add remediation if available
    remediation = finding.get("remediation", [])
    if remediation and isinstance(remediation, list):
        section += "\n**Remediation:**\n"
        for step in remediation[:3]:
            section += f"- {step}\n"

    # Add CVSS if available (Tier 3)
    cvss = finding.get("cvss_score")
    if cvss:
        section += f"\n**CVSS Score:** {cvss}\n"

    return section


def generate_pr_comment(results: Dict[str, Any], repo_url: str = "") -> str:
    """
    Generate a full PR comment from scan results.

    Args:
        results: Scan results dict with findings, stats, etc.
        repo_url: Optional repo URL for linking

    Returns:
        GitHub-flavored markdown string
    """
    findings = results.get("findings", [])
    stats = results.get("stats", {})
    scan_type = results.get("scan_type", "3")

    # Header
    header = "## 🔒 SentinAI Security Review\n\n"

    # Summary section
    if not findings:
        header += "✅ **No security vulnerabilities detected.**\n\n"
        header += f"Scanned {stats.get('files_scanned', 0)} files using Tier {scan_type} analysis.\n"
        return header

    total = len(findings)
    high = sum(1 for f in findings if f.get("severity", "").upper() == "HIGH")
    medium = sum(1 for f in findings if f.get("severity", "").upper() == "MEDIUM")
    low = sum(1 for f in findings if f.get("severity", "").upper() == "LOW")

    summary = f"""
⚠️ **{total} security finding(s) detected**

| Severity | Count |
|----------|-------|
| 🔴 High | {high} |
| 🟠 Medium | {medium} |
| 🟡 Low | {low} |

**Scan Details:**
- Files scanned: {stats.get('files_scanned', 'N/A')}
- Analysis tier: Tier {scan_type}
- Filtered findings: {results.get('_filtered_count', 0)} false positives removed

---

"""

    # Findings details
    findings_section = "### 🚨 Findings\n\n"

    # Show high severity first
    high_findings = [f for f in findings if f.get("severity", "").upper() == "HIGH"]
    other_findings = [f for f in findings if f.get("severity", "").upper() != "HIGH"]

    for finding in high_findings + other_findings[:10]:  # Limit to 10 total for readability
        findings_section += format_finding_for_pr(finding)
        findings_section += "\n---\n\n"

    if len(findings) > 10:
        findings_section += f"\n*... and {len(findings) - 10} more findings. [View full report]({repo_url}/security/sentinai)*\n"

    # Footer
    footer = f"""
---

*Generated by [SentinAI](https://github.com/anthropics/claude-code-security-review) • Tier {scan_type} Analysis • {stats.get('files_scanned', 0)} files scanned*
"""

    return header + summary + findings_section + footer


def generate_inline_comment(finding: Dict[str, Any]) -> Dict[str, Any]:
    """
    Generate inline PR comment data for a finding.

    Returns:
        Dict with path, line, body for GitHub API
    """
    severity = finding.get("severity", "MEDIUM")
    finding_type = finding.get("type", "Unknown")
    description = finding.get("description", finding.get("reason", ""))[:200]

    severity_icons = {
        "HIGH": "🔴",
        "MEDIUM": "🟠",
        "LOW": "🟡"
    }
    icon = severity_icons.get(severity.upper(), "⚪")

    body = f"{icon} **{severity}**: {finding_type}\n\n{description}"

    return {
        "path": finding.get("file", finding.get("filename", "")),
        "line": finding.get("line", 1),
        "body": body,
        "severity": severity
    }


def generate_summary_table(findings: List[Dict[str, Any]]) -> str:
    """Generate a markdown table of findings."""
    if not findings:
        return "✅ No security vulnerabilities detected."

    lines = [
        "| Severity | Type | File | Line | Description |",
        "|----------|------|------|------|-------------|"
    ]

    for f in findings[:20]:
        sev = f.get("severity", "MEDIUM")[:4]
        ftype = f.get("type", "Unknown")[:20]
        file_path = f.get("file", f.get("filename", ""))[:30]
        line = f.get("line", 0)
        desc = f.get("description", f.get("reason", ""))[:40].replace("|", "\\|")

        lines.append(f"| {sev} | {ftype} | `{file_path}` | {line} | {desc}... |")

    return "\n".join(lines)


def _detect_language(file_path: str) -> str:
    """Detect programming language from file extension."""
    ext_map = {
        '.py': 'python',
        '.js': 'javascript',
        '.ts': 'typescript',
        '.tsx': 'tsx',
        '.jsx': 'jsx',
        '.java': 'java',
        '.c': 'c',
        '.cpp': 'cpp',
        '.go': 'go',
        '.rs': 'rust',
        '.php': 'php',
        '.rb': 'ruby',
        '.swift': 'swift',
        '.kt': 'kotlin',
        '.html': 'html',
        '.css': 'css',
        '.sql': 'sql',
        '.yaml': 'yaml',
        '.yml': 'yaml',
        '.json': 'json',
        '.sh': 'bash',
        '.md': 'markdown',
    }

    from pathlib import Path
    ext = Path(file_path).suffix.lower()
    return ext_map.get(ext, '')


def format_for_sarif(results: Dict[str, Any]) -> Dict[str, Any]:
    """
    Convert results to SARIF format for GitHub Advanced Security integration.
    """
    findings = results.get("findings", [])

    runs = [{
        "tool": {
            "driver": {
                "name": "SentinAI",
                "version": "2.0",
                "informationUri": "https://github.com/your-org/sentinai"
            }
        },
        "results": []
    }]

    for finding in findings:
        sarif_result = {
            "ruleId": finding.get("type", "UNKNOWN"),
            "level": _severity_to_sarif_level(finding.get("severity", "medium")),
            "message": {
                "text": finding.get("description", finding.get("reason", ""))
            },
            "locations": [{
                "physicalLocation": {
                    "artifactLocation": {
                        "uri": finding.get("file", finding.get("filename", ""))
                    },
                    "region": {
                        "startLine": finding.get("line", 1)
                    }
                }
            }]
        }
        runs[0]["results"].append(sarif_result)

    return {
        "$schema": "https://raw.githubusercontent.com/oasis-tcs/sarif-spec/master/Schemata/sarif-schema-2.1.0.json",
        "version": "2.1.0",
        "runs": runs
    }


def _severity_to_sarif_level(severity: str) -> str:
    """Convert SentinAI severity to SARIF level."""
    mapping = {
        "CRITICAL": "error",
        "HIGH": "error",
        "MEDIUM": "warning",
        "LOW": "note"
    }
    return mapping.get(severity.upper(), "warning")
